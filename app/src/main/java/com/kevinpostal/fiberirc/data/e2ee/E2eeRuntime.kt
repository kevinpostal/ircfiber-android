    BackupWithPasskey("backupWithPasskey"),
    BackupWithRecoveryKey("backupWithRecoveryKey"),
    RestoreBackup("restoreBackup"),
    DeleteBackup("deleteBackup"),
    CreateLinkOffer("createLinkOffer"),
    AcceptLinkOffer("acceptLinkOffer"),
    SafetyNumber("safetyNumber"),
    ImportOwnKey("importOwnKey"),
    OwnKeyInfo("ownKeyInfo"),
    OldKeyInfo("oldKeyInfo"),
