/** The bridge envelope version (`MOBILE_ABI` in the site's `lib/e2ee/mobile.ts`, `abi` in `runtime.json`). */
const val E2EE_ABI = 1

/** The only origin the runtime document is served from ([WebViewAssetLoader]'s reserved domain, HTTPS only). */
internal const val E2EE_ORIGIN = "https://${WebViewAssetLoader.DEFAULT_DOMAIN}"

/** URL path prefix of the packaged runtime (`app/src/main/assets/e2ee/`, generated by the site's `build:mobile-e2ee`). */
internal const val E2EE_PATH_PREFIX = "/assets/e2ee/"

/** Asset directory holding `runtime.html` + `runtime.json` (and, in debug builds only, the smoke document). */
internal const val E2EE_ASSET_DIR = "e2ee"

/** Name of the JS object [WebViewCompat.addWebMessageListener] injects; the same name as iOS's script handler. */
internal const val E2EE_HANDLER = "ircfiberE2ee"

/** The production document. */
internal const val RUNTIME_DOCUMENT = "runtime.html"

/**
