    PinPeerKey("pinPeerKey"),
    PeerKeyInfo("peerKeyInfo"),
    MarkPeerVerified("markPeerVerified"),
    InstallOrgCertificate("installOrgCertificate"),
    Unlock("unlock"),
    Flush("flush"),
    Shutdown("shutdown"),
}

/** Runtime → native host calls: the closed list of `mobile.ts` (`HOST_CALL_OPS`). Anything else is refused. */
enum class E2eeHostOp(val wire: String) {
    HttpRequest("http.request"),
    StorageGetMeta("storage.getMeta"),
    StorageSetMeta("storage.setMeta"),
    StorageDeleteMeta("storage.deleteMeta"),
    StorageListMeta("storage.listMeta"),
    StorageLoadMlsState("storage.loadMlsState"),
    StorageSaveMlsState("storage.saveMlsState"),
    StorageArchiveGet("storage.archiveGet"),
    StorageArchivePut("storage.archivePut"),
    StorageArchiveExportAll("storage.archiveExportAll"),
    StorageArchiveImport("storage.archiveImport"),
    StorageImportRecovery("storage.importRecovery"),
    StorageArchivePrune("storage.archivePrune"),
    StorageE2eeDbExists("storage.e2eeDbExists"),
    StorageDeleteE2eeDb("storage.deleteE2eeDb"),
    PrefsSetBuffer("prefs.setBuffer"),
    PrefsSetLocal("prefs.setLocal"),
    IrcSendWho("irc.sendWho"),
    TransportSendWire("transport.sendWire"),
    PasskeyPrf("passkey.prf"),
    ;

    companion object {
        private val byWire = entries.associateBy(E2eeHostOp::wire)
        fun fromWire(wire: String): E2eeHostOp? = byWire[wire]
    }
}

/** One runtime-origin request (`j:*` id) of the current [generation]. */
data class E2eeHostCall(val generation: Long, val id: String, val op: E2eeHostOp, val args: JsonObject)

/**
 * A refused or failed bridge operation, both directions: thrown by [E2eeRuntime.dispatch] for an `ok:false`
 * response (`code`/`message`/`status` as the runtime reported them), and thrown by an [E2eeHostCallHandler] to
 * answer a host call with that error (`uncertain_delivery`, `session_expired`, `storage_failed`, …).
 */
class E2eeBridgeException(val code: String, message: String, val status: Int? = null) : Exception(message)

/**
 * Serves the runtime's host calls (phase 3: native HTTP, encrypted store, preferences, IRC transport, passkey PRF).
 * Runs on the main thread; switch dispatchers for blocking work. Return the JSON `result` (JsonNull for none), or
 * throw [E2eeBridgeException] to reply an error. Any other exception replies `host_error`.
 */
fun interface E2eeHostCallHandler {
    suspend fun handle(call: E2eeHostCall): JsonElement
}

/** Runtime notifications of the current generation (`mobile.ts` `RuntimeEvent`). */
sealed interface E2eeRuntimeEvent {
    val generation: Long
    val payload: JsonObject

    /** `{ui,ktAlarm,deviceId,policy}` status snapshot. */
    data class State(override val generation: Long, override val payload: JsonObject) : E2eeRuntimeEvent

    /** `{networkId,buffer,id,msgid?,message}`: locate the row by stable `id`, then `msgid`. */
    data class ReplaceRow(override val generation: Long, override val payload: JsonObject) : E2eeRuntimeEvent
}

/** Main-thread callbacks of one [E2eeRuntime]. */
interface E2eeRuntimeListener {
    fun onEvent(event: E2eeRuntimeEvent)

    /** The runtime is gone for good (renderer crash/kill, document restart, [E2eeRuntime.destroy] excluded). A
     *  replacement must be started from committed storage; in-flight requests already failed with `runtime_gone`. */
    fun onTerminated(cause: E2eeRuntimeUnavailable)
}

/** Why the local encryption runtime can't run. Never a cue to load a remote page or loosen the CSP. */
class E2eeRuntimeUnavailable(val reason: Reason, detail: String) : Exception("${reason.name}: $detail") {
    enum class Reason {
        /** The installed Android System WebView lacks WEB_MESSAGE_LISTENER or failed the capability gate. */
        WebViewUpdateRequired,

        /** No WebView provider is installed/enabled. */
        WebViewMissing,

        /** `runtime.html`/`runtime.json` missing, mismatched or of another ABI. */
        ResourceInvalid,

        /** The document didn't load or report ready. */
        LoadFailed,

        /** The renderer crashed/was killed, or the document restarted. */
        RendererGone,

        /** [E2eeRuntime.destroy] was called. */
        Destroyed,
    }

    /** What the encryption UI shows; sending stays blocked. */
    val userMessage: String
        get() = when (reason) {
            Reason.WebViewUpdateRequired, Reason.WebViewMissing -> "Update Android System WebView to use encryption"
            else -> "Encryption is unavailable"
        }
}

/** The runtime's ready report: ABI and the capability gate it passed. */
data class E2eeRuntimeReady(val abi: Int, val capabilities: Map<String, Boolean>, val smoke: Boolean)

/**
 * The app process's single encryption-runtime WebView: the packaged, hash-verified `assets/e2ee/runtime.html`
 * served by [WebViewAssetLoader] at [E2EE_ORIGIN], never attached to a window, talking JSON only through the
 * [E2EE_HANDLER] web-message listener (exact origin, main frame, exact document URL). Navigation, subframes,
 * popups, downloads, permission prompts and every other resource load are refused; file/content access and mixed
 * content are off; web-contents debugging is on only in debug builds.
 *
 * Envelopes (ABI 1): native requests `{v,generation,id:"n:*",op,args}` → `BridgeResponse`; runtime host calls
 * `{v,generation,id:"j:*",op,args}` → `{v,generation,id,ok,result?|error?}`; events `{v,generation,event,payload}`.
 * Every native message goes through `JavaScriptReplyProxy.postMessage` as a JSON string, never `evaluateJavascript`.
 *
 * Generations fence account sessions: [beginGeneration] advances it (failing older pending requests), requests
 * carry it, and host calls/events/responses of any other generation are refused or dropped.
 *
 * State is main-thread confined; the suspend functions may be called from any thread.
 */
class E2eeRuntime @VisibleForTesting internal constructor(
    context: Context,
    private val hostCalls: E2eeHostCallHandler,
    private val listener: E2eeRuntimeListener,
    /** Asset under [E2EE_ASSET_DIR]; tests use the debug-only smoke document. */
    private val document: String,
) {
    constructor(context: Context, hostCalls: E2eeHostCallHandler, listener: E2eeRuntimeListener) :
        this(context, hostCalls, listener, RUNTIME_DOCUMENT)

    private class PendingRequest(val generation: Long, val reply: CompletableDeferred<JsonElement>)

    private val app = context.applicationContext
    private val mainHandler = Handler(Looper.getMainLooper())
    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.Main.immediate)
    private val documentUrl = E2EE_ORIGIN + E2EE_PATH_PREFIX + document

    private var started = false
    private var webView: WebView? = null
    private var replyProxy: JavaScriptReplyProxy? = null
    private var ready: CompletableDeferred<E2eeRuntimeReady>? = null
    private var failure: E2eeRuntimeUnavailable? = null
    private var generation = -1L
    private var nextRequest = 0L
    private val pending = HashMap<String, PendingRequest>()

    /**
     * Verifies the packaged document against its manifest, creates the WebView, loads the document and waits for its
     * ready report (secure context, WebCrypto, random, WASM compiled under the CSP). Throws [E2eeRuntimeUnavailable];
     * on [E2eeRuntimeUnavailable.Reason.WebViewUpdateRequired] the app shows [E2eeRuntimeUnavailable.userMessage]
     * and blocks encrypted sends. Call once per instance.
     */
    suspend fun start(): E2eeRuntimeReady {
        val bytes = withContext(Dispatchers.IO) { loadVerifiedDocument(app, document) }
        val awaiting = withContext(Dispatchers.Main.immediate) {
            check(!started) { "E2eeRuntime.start called twice" }
            started = true
            failure?.let { throw it }
            check(active == null) { "another E2eeRuntime is live in this process" }
            val deferred = CompletableDeferred<E2eeRuntimeReady>()
            ready = deferred
            try {
                createWebView(bytes)
            } catch (e: E2eeRuntimeUnavailable) {
                terminate(e, notify = false)
                throw e
            }
            deferred
        }
        try {
            return withTimeout(READY_TIMEOUT_MS) { awaiting.await() }
        } catch (e: TimeoutCancellationException) {
            val cause = E2eeRuntimeUnavailable(E2eeRuntimeUnavailable.Reason.LoadFailed, "runtime did not report ready")
            withContext(NonCancellable + Dispatchers.Main.immediate) { terminate(cause, notify = false) }
            throw cause
        } catch (e: E2eeRuntimeUnavailable) {
            withContext(NonCancellable + Dispatchers.Main.immediate) { terminate(e, notify = false) }
            throw e
        }
    }

    /** Starts a new account session generation (before `bootstrap`); pending requests of older ones fail. */
    suspend fun beginGeneration(): Long = withContext(Dispatchers.Main.immediate) {
        failure?.let { throw it }
        generation += 1
        val stale = pending.filterValues { it.generation < generation }
        for ((id, request) in stale) {
            pending.remove(id)
            request.reply.completeExceptionally(
                E2eeBridgeException("stale_generation", "request from a previous generation"),
            )
        }
        generation
    }

    /** Sends one native request of [generation] and returns its `result` (JsonNull for none); `ok:false` throws
     *  [E2eeBridgeException]. Cancelling the caller abandons the reply, not the runtime operation. */
    suspend fun dispatch(generation: Long, op: E2eeOp, args: JsonObject = EMPTY_ARGS): JsonElement =
        dispatchWire(generation, op.wire, args)

    @VisibleForTesting
    internal suspend fun dispatchWire(generation: Long, op: String, args: JsonObject): JsonElement {
        val reply = CompletableDeferred<JsonElement>()
        val id = withContext(Dispatchers.Main.immediate) {
            failure?.let { throw E2eeBridgeException("runtime_gone", it.message ?: "encryption runtime unavailable") }
            val proxy = replyProxy ?: throw E2eeBridgeException("not_started", "encryption runtime not started")
            if (generation != this@E2eeRuntime.generation) {
                throw E2eeBridgeException("stale_generation", "request from a previous generation")
            }
            val requestId = "n:${++nextRequest}"
            pending[requestId] = PendingRequest(generation, reply)
            proxy.postMessage(
                buildJsonObject {
                    put("v", E2EE_ABI)
                    put("generation", generation)
                    put("id", requestId)
                    put("op", op)
                    put("args", args)
                }.toString(),
            )
            requestId
        }
        try {
            return reply.await()
        } finally {
            if (!reply.isCompleted) withContext(NonCancellable + Dispatchers.Main.immediate) { pending.remove(id) }
        }
    }

    /** Tears the WebView down; pending requests fail with `runtime_gone`. Idempotent, any thread. */
    fun destroy() {
        val cause = E2eeRuntimeUnavailable(E2eeRuntimeUnavailable.Reason.Destroyed, "runtime destroyed")
        if (Looper.myLooper() == Looper.getMainLooper()) {
            terminate(cause, notify = false)
        } else {
            mainHandler.post { terminate(cause, notify = false) }
        }
    }

    @VisibleForTesting
    @MainThread
    internal fun webViewForTest(): WebView? = webView

    // ── WebView ────────────────────────────────────────────────────────────

    @MainThread
    private fun createWebView(bytes: ByteArray) {
        val view = try {
            if (!WebViewFeature.isFeatureSupported(WebViewFeature.WEB_MESSAGE_LISTENER)) {
                throw E2eeRuntimeUnavailable(
                    E2eeRuntimeUnavailable.Reason.WebViewUpdateRequired,
                    "WebView lacks WEB_MESSAGE_LISTENER",
                )
            }
            WebView(app)
        } catch (e: E2eeRuntimeUnavailable) {
            throw e
        } catch (e: RuntimeException) {
            // No/disabled WebView provider (AndroidRuntimeException, MissingWebViewPackageException).
            throw E2eeRuntimeUnavailable(E2eeRuntimeUnavailable.Reason.WebViewMissing, e.javaClass.simpleName)
        }
        WebView.setWebContentsDebuggingEnabled(BuildConfig.DEBUG)
        configure(view.settings)
        val loader = WebViewAssetLoader.Builder()
            .setDomain(WebViewAssetLoader.DEFAULT_DOMAIN)
            .setHttpAllowed(false)
            .addPathHandler(E2EE_PATH_PREFIX) { path -> if (path == document) documentResponse(bytes) else null }
            .build()
        view.webViewClient = RuntimeClient(loader)
        view.webChromeClient = RuntimeChrome
        view.setDownloadListener { _, _, _, _, _ -> }
        view.isFocusable = false
        view.isFocusableInTouchMode = false
        view.importantForAccessibility = android.view.View.IMPORTANT_FOR_ACCESSIBILITY_NO_HIDE_DESCENDANTS
        WebViewCompat.addWebMessageListener(view, E2EE_HANDLER, setOf(E2EE_ORIGIN), messageListener)
        webView = view
        active = this
        view.loadUrl(documentUrl)
    }

    @SuppressLint("SetJavaScriptEnabled")
    @Suppress("DEPRECATION")
    private fun configure(settings: WebSettings) {
        settings.javaScriptEnabled = true
        settings.javaScriptCanOpenWindowsAutomatically = false
        settings.setSupportMultipleWindows(false)
        settings.allowFileAccess = false
        settings.allowContentAccess = false
        settings.allowFileAccessFromFileURLs = false
        settings.allowUniversalAccessFromFileURLs = false
        settings.mixedContentMode = WebSettings.MIXED_CONTENT_NEVER_ALLOW
        // No durable secret (or any) state in the WebView: the native encrypted store holds it all.
        settings.domStorageEnabled = false
        settings.databaseEnabled = false
        settings.saveFormData = false
        settings.cacheMode = WebSettings.LOAD_NO_CACHE
        settings.setGeolocationEnabled(false)
        settings.safeBrowsingEnabled = false // nothing remote to check; avoids URL lookups leaving the device
        settings.blockNetworkImage = true
        settings.loadsImagesAutomatically = false
        settings.mediaPlaybackRequiresUserGesture = true
        settings.setSupportZoom(false)
    }

    private fun documentResponse(bytes: ByteArray) = WebResourceResponse(
        "text/html",
        "utf-8",
        200,
        "OK",
        mapOf(
            "Cache-Control" to "no-store",
            "X-Content-Type-Options" to "nosniff",
            "Referrer-Policy" to "no-referrer",
        ),
        ByteArrayInputStream(bytes),
    )

    private inner class RuntimeClient(private val loader: WebViewAssetLoader) : WebViewClient() {
        // Background thread: touches only immutable state.
        override fun shouldInterceptRequest(view: WebView, request: WebResourceRequest): WebResourceResponse? {
            if (request.isForMainFrame && request.method == "GET" && request.url.toString() == documentUrl) {
                loader.shouldInterceptRequest(request.url)?.let { return it }
            }
            return denied()
        }

        override fun shouldOverrideUrlLoading(view: WebView, request: WebResourceRequest): Boolean = true

        override fun onReceivedError(view: WebView, request: WebResourceRequest, error: WebResourceError) {
            if (view === webView && request.isForMainFrame) {
                loadFailed("document load error ${error.errorCode}")
            }
        }

        override fun onReceivedHttpError(view: WebView, request: WebResourceRequest, response: WebResourceResponse) {
            if (view === webView && request.isForMainFrame) loadFailed("document HTTP ${response.statusCode}")
        }

        override fun onRenderProcessGone(view: WebView, detail: RenderProcessGoneDetail): Boolean {
            if (view === webView) {
                terminate(
                    E2eeRuntimeUnavailable(
                        E2eeRuntimeUnavailable.Reason.RendererGone,
                        if (detail.didCrash()) "renderer crashed" else "renderer killed",
                    ),
                    notify = true,
                )
            } else {
                view.destroy()
            }
            return true
        }
    }

    private fun loadFailed(detail: String) {
        val deferred = ready
        val cause = E2eeRuntimeUnavailable(E2eeRuntimeUnavailable.Reason.LoadFailed, detail)
        if (deferred != null && !deferred.isCompleted) deferred.completeExceptionally(cause) else terminate(cause, notify = true)
    }

    private object RuntimeChrome : WebChromeClient() {
        override fun onCreateWindow(view: WebView, isDialog: Boolean, isUserGesture: Boolean, resultMsg: Message): Boolean =
            false

        override fun onJsAlert(view: WebView, url: String, message: String, result: JsResult): Boolean {
            result.cancel()
            return true
        }

        override fun onJsConfirm(view: WebView, url: String, message: String, result: JsResult): Boolean {
            result.cancel()
            return true
        }

        override fun onJsPrompt(
            view: WebView,
            url: String,
            message: String,
            defaultValue: String,
            result: JsPromptResult,
        ): Boolean {
            result.cancel()
            return true
        }

        override fun onJsBeforeUnload(view: WebView, url: String, message: String, result: JsResult): Boolean {
            result.cancel()
            return true
        }

        override fun onPermissionRequest(request: PermissionRequest) = request.deny()

        override fun onGeolocationPermissionsShowPrompt(origin: String, callback: GeolocationPermissions.Callback) =
            callback.invoke(origin, false, false)

        // Console output can carry message metadata: logcat only in debug builds.
        override fun onConsoleMessage(message: ConsoleMessage): Boolean {
            if (BuildConfig.DEBUG) Log.d(TAG, "${message.messageLevel()}: ${message.message()}")
            return true
        }
    }

    // ── messages ───────────────────────────────────────────────────────────

    private val messageListener = WebViewCompat.WebMessageListener { view, message, sourceOrigin, isMainFrame, proxy ->
        if (view !== webView || failure != null || !isMainFrame || !isRuntimeOrigin(sourceOrigin)) {
            return@WebMessageListener
        }
        if (view.url != documentUrl) return@WebMessageListener
        if (message.type != WebMessageCompat.TYPE_STRING) return@WebMessageListener
        val data = message.data ?: return@WebMessageListener
        val envelope = try {
            Json.parseToJsonElement(data) as? JsonObject
        } catch (_: SerializationException) {
            null
        } ?: return@WebMessageListener
        receive(envelope, proxy)
    }

    @MainThread
    private fun receive(envelope: JsonObject, proxy: JavaScriptReplyProxy) {
        if (envelope["v"].primitive()?.intOrNull != E2EE_ABI) return
        val gen = envelope["generation"].primitive()?.longOrNull ?: return
        val event = envelope["event"].string()
        if (event != null) {
            receiveEvent(gen, event, envelope["payload"], proxy)
            return
        }
        val id = envelope["id"].string() ?: return
        when {
            id.startsWith("n:") && envelope.containsKey("ok") -> receiveResponse(gen, id, envelope)
            id.startsWith("j:") && id.length > 2 -> receiveHostCall(gen, id, envelope)
        }
    }

    private fun receiveEvent(gen: Long, event: String, payload: JsonElement?, proxy: JavaScriptReplyProxy) {
        if (event == "ready") {
            if (gen != -1L) return
            if (replyProxy != null) {
                // A second ready means the document restarted: its sessions and pending calls are gone.
                terminate(
                    E2eeRuntimeUnavailable(E2eeRuntimeUnavailable.Reason.RendererGone, "runtime document restarted"),
                    notify = true,
                )
                return
            }
            replyProxy = proxy
            val deferred = ready ?: return
            val result = runCatching { parseReady(payload as? JsonObject) }
            result.fold(deferred::complete, deferred::completeExceptionally)
            return
        }
        if (gen != generation || payload !is JsonObject) return
        when (event) {
            "state" -> listener.onEvent(E2eeRuntimeEvent.State(gen, payload))
            "replaceRow" -> listener.onEvent(E2eeRuntimeEvent.ReplaceRow(gen, payload))
        }
    }

    private fun receiveResponse(gen: Long, id: String, envelope: JsonObject) {
        val request = pending[id] ?: return
        if (request.generation != gen) return
        pending.remove(id)
        if (envelope["ok"].primitive()?.booleanOrNull == true) {
            request.reply.complete(envelope["result"] ?: JsonNull)
        } else {
            val error = envelope["error"] as? JsonObject
            request.reply.completeExceptionally(
                E2eeBridgeException(
                    error?.get("code").string()?.takeIf(String::isNotEmpty) ?: "failed",
                    error?.get("message").string() ?: "encryption operation failed",
                    error?.get("status").primitive()?.intOrNull,
                ),
            )
        }
    }

    private fun receiveHostCall(gen: Long, id: String, envelope: JsonObject) {
        val opWire = envelope["op"].string() ?: return
        val op = E2eeHostOp.fromWire(opWire)
        if (op == null) {
            postToRuntime(errorReply(gen, id, "unknown_op", "unknown host operation"))
            return
        }
        if (gen != generation) {
            postToRuntime(errorReply(gen, id, "stale_generation", "host call from a previous generation"))
            return
        }
        val args = envelope["args"] as? JsonObject ?: EMPTY_ARGS
        scope.launch {
            val reply = try {
                val result = hostCalls.handle(E2eeHostCall(gen, id, op, args))
                buildJsonObject {
                    put("v", E2EE_ABI)
                    put("generation", gen)
                    put("id", id)
                    put("ok", true)
                    put("result", result)
                }
            } catch (e: CancellationException) {
                throw e
            } catch (e: E2eeBridgeException) {
                errorReply(gen, id, e.code, e.message ?: e.code, e.status)
            } catch (e: Exception) {
                errorReply(gen, id, "host_error", "${op.wire} failed: ${e.javaClass.simpleName}")
            }
            postToRuntime(reply)
        }
    }

    @MainThread
    private fun postToRuntime(message: JsonObject) {
        if (failure != null) return
        replyProxy?.postMessage(message.toString())
    }

    @MainThread
    private fun terminate(cause: E2eeRuntimeUnavailable, notify: Boolean) {
        if (failure != null) return
        failure = cause
        ready?.let { if (!it.isCompleted) it.completeExceptionally(cause) }
        val gone = E2eeBridgeException("runtime_gone", cause.message ?: "encryption runtime unavailable")
        for (request in pending.values) request.reply.completeExceptionally(gone)
        pending.clear()
        scope.cancel()
        replyProxy = null
        webView?.let { view ->
            runCatching { WebViewCompat.removeWebMessageListener(view, E2EE_HANDLER) }
            view.stopLoading()
            view.destroy()
        }
        webView = null
        if (active === this) active = null
        if (cause.reason != E2eeRuntimeUnavailable.Reason.Destroyed) Log.w(TAG, "encryption runtime stopped: ${cause.reason}")
        if (notify) listener.onTerminated(cause)
    }

    companion object {
        private const val TAG = "E2eeRuntime"
        private const val READY_TIMEOUT_MS = 30_000L
        private val EMPTY_ARGS = JsonObject(emptyMap())
        private val REQUIRED_CAPABILITIES = listOf("secureContext", "webCrypto", "random", "wasm")

        /** The process's one live runtime (main-thread confined). */
        private var active: E2eeRuntime? = null

        private fun isRuntimeOrigin(origin: Uri): Boolean =
            origin.scheme == "https" && origin.host == WebViewAssetLoader.DEFAULT_DOMAIN && origin.port == -1 &&
                origin.path.isNullOrEmpty()

        private fun denied() = WebResourceResponse(
            "text/plain",
            "utf-8",
            403,
            "Forbidden",
            emptyMap(),
            ByteArrayInputStream(ByteArray(0)),
        )

        private fun errorReply(gen: Long, id: String, code: String, message: String, status: Int? = null) =
            buildJsonObject {
                put("v", E2EE_ABI)
                put("generation", gen)
                put("id", id)
                put("ok", false)
                put(
                    "error",
                    buildJsonObject {
                        put("code", code)
                        put("message", message)
                        if (status != null) put("status", status)
                    },
                )
            }

        private fun parseReady(payload: JsonObject?): E2eeRuntimeReady {
            payload ?: throw E2eeRuntimeUnavailable(E2eeRuntimeUnavailable.Reason.LoadFailed, "ready without payload")
            val abi = payload["abi"].primitive()?.intOrNull
            if (abi != E2EE_ABI) {
                throw E2eeRuntimeUnavailable(E2eeRuntimeUnavailable.Reason.ResourceInvalid, "runtime ABI $abi")
            }
            val caps = (payload["capabilities"] as? JsonObject).orEmpty()
                .mapValues { (_, v) -> v.primitive()?.booleanOrNull == true }
            val missing = REQUIRED_CAPABILITIES.filter { caps[it] != true }
            if (payload["ok"].primitive()?.booleanOrNull != true || missing.isNotEmpty()) {
                // Detail is the runtime's own capability error; it carries no user content.
                val error = payload["error"].string() ?: "runtime not ready"
                throw E2eeRuntimeUnavailable(
                    E2eeRuntimeUnavailable.Reason.WebViewUpdateRequired,
                    if (missing.isEmpty()) error else "$error; missing ${missing.joinToString()}",
                )
            }
            return E2eeRuntimeReady(E2EE_ABI, caps, payload["smoke"].primitive()?.booleanOrNull == true)
        }

        /**
         * Reads `assets/e2ee/<document>` and checks it against `<document stem>.json`
         * (`{abi,file,sha256,size,handler}`) before anything loads it; the returned bytes are the ones served.
         */
        internal fun loadVerifiedDocument(context: Context, document: String): ByteArray {
            fun invalid(detail: String) = E2eeRuntimeUnavailable(E2eeRuntimeUnavailable.Reason.ResourceInvalid, detail)
            val manifestName = document.substringBeforeLast('.') + ".json"
            val (bytes, manifestText) = try {
                val assets = context.assets
                val bytes = assets.open("$E2EE_ASSET_DIR/$document").use { it.readBytes() }
                val manifest = assets.open("$E2EE_ASSET_DIR/$manifestName").use { it.readBytes().decodeToString() }
                bytes to manifest
            } catch (e: IOException) {
                throw invalid("missing $E2EE_ASSET_DIR/$document or $manifestName")
            }
            val manifest = try {
                Json.parseToJsonElement(manifestText) as? JsonObject
            } catch (_: SerializationException) {
                null
            } ?: throw invalid("$manifestName is not a JSON object")
            if (manifest["abi"].primitive()?.intOrNull != E2EE_ABI) throw invalid("$manifestName ABI mismatch")
            if (manifest["file"].string() != document) throw invalid("$manifestName names another file")
            if (manifest["handler"].string() != E2EE_HANDLER) throw invalid("$manifestName handler mismatch")
            if (manifest["size"].primitive()?.longOrNull != bytes.size.toLong()) throw invalid("$document size mismatch")
            val digest = MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }
            if (manifest["sha256"].string()?.lowercase() != digest) throw invalid("$document SHA-256 mismatch")
            return bytes
        }

        private fun JsonElement?.primitive(): JsonPrimitive? = this as? JsonPrimitive

        private fun JsonElement?.string(): String? = (this as? JsonPrimitive)?.takeIf { it.isString }?.content
    }
