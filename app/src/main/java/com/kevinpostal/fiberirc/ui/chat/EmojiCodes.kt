    private val colonCode = Regex(":([a-z0-9_+-]+):")

    /** Replaces each known `:name:` with its emoji and leaves unknown codes as typed (`emoji.ts` `replaceColons`). */
    fun replaceColons(s: String): String {
        if (':' !in s) return s
        return colonCode.replace(s) { m -> map[m.groupValues[1]] ?: m.value }
    }
